// 破甲工作台 · preload —— 渲染层唯一的对外通道
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('pojia', {
  boot: () => ipcRenderer.invoke('pojia:boot'),
  status: (targets) => ipcRenderer.invoke('pojia:status', targets),
  test: (targets) => ipcRenderer.invoke('pojia:test', targets),
  route: (sentence) => ipcRenderer.invoke('pojia:route', sentence),
  tx: (argv) => ipcRenderer.invoke('pojia:tx', argv),
  diff: (argv) => ipcRenderer.invoke('pojia:diff', argv),
  patches: (target) => ipcRenderer.invoke('pojia:patches', target),
  cat: (argv) => ipcRenderer.invoke('pojia:cat', argv),
  read: (argv) => ipcRenderer.invoke('pojia:read', argv),
  write: (argv) => ipcRenderer.invoke('pojia:write', argv),
  prompts: () => ipcRenderer.invoke('pojia:prompts'),
  promptRead: (id) => ipcRenderer.invoke('pojia:promptRead', id),
  promptWrite: (id, b64) => ipcRenderer.invoke('pojia:promptWrite', { id, b64 }),
  promptNew: (name) => ipcRenderer.invoke('pojia:promptNew', name),
  promptDelete: (id) => ipcRenderer.invoke('pojia:promptDelete', id),
  instrList: (seat) => ipcRenderer.invoke('pojia:instrList', seat),
  instrApply: (seat, name) => ipcRenderer.invoke('pojia:instrApply', { seat, name }),
  instrDisable: (seat) => ipcRenderer.invoke('pojia:instrDisable', seat),
  instrToggle: (seat, name, on) => ipcRenderer.invoke('pojia:instrToggle', { seat, name, on }),
  docs: (agent) => ipcRenderer.invoke('pojia:docs', agent),
  docRead: (id) => ipcRenderer.invoke('pojia:docRead', id),
  docWrite: (id, b64) => ipcRenderer.invoke('pojia:docWrite', { id, b64 }),
  docNew: (agent, cat, name) => ipcRenderer.invoke('pojia:docNew', { agent, cat, name }),
  docDelete: (id) => ipcRenderer.invoke('pojia:docDelete', id),
  docToggle: (id) => ipcRenderer.invoke('pojia:docToggle', id),
  docToggleMany: (items) => ipcRenderer.invoke('pojia:docToggleMany', items),
  docMemo: (id, memo) => ipcRenderer.invoke('pojia:docMemo', { id, memo }),
  run: (action, targets, flags) => ipcRenderer.invoke('pojia:run', { action, targets, flags }),
  abort: () => ipcRenderer.send('pojia:abort'),
  setPython: (exe) => ipcRenderer.invoke('pojia:setPython', exe),
  pickPython: () => ipcRenderer.invoke('pojia:pickPython'),
  openPath: (target) => ipcRenderer.invoke('pojia:openPath', target),
  readLog: () => ipcRenderer.invoke('pojia:readLog'),
  openConsole: () => ipcRenderer.invoke('pojia:openConsole'),
  checkUpdate: () => ipcRenderer.invoke('pojia:checkUpdate'),
  onLog: (cb) => { ipcRenderer.on('pojia:log', (_e, evt) => cb(evt)); },
  win: (act) => ipcRenderer.send('pojia:win', act),
});
